// Splits the generated types.gen.ts into one file per API domain.
//
// @hey-api/openapi-ts emits every model and every operation's wire types into a
// single types.gen.ts (~2500 lines). This post-processor runs as part of
// `bun run generate-client`, so the split survives regeneration instead of
// being a hand edit. types.gen.ts becomes a barrel, which keeps sdk.gen.ts and
// index.ts importing from the same path.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const clientDir = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "client",
)
const typesPath = join(clientDir, "types.gen.ts")
const outDir = join(clientDir, "types")
const HEADER = "// This file is auto-generated by @hey-api/openapi-ts\n"

// Order matters: Sop before Step (SopStepRead), Station before Step, etc.
const MODEL_PREFIXES = [
  ["Sop", "sops"],
  ["Station", "stations"],
  ["Step", "executions"],
  ["Alarm", "alarms"],
  ["Camera", "cameras"],
  ["Execution", "executions"],
  ["Event", "events"],
  ["Evidence", "evidence"],
  ["Health", "health"],
  ["Runtime", "runtimes"],
  ["Matched", "executions"],
  ["ModelRef", "events"],
  ["ProcessingResult", "events"],
  ["ReasonCode", "executions"],
  ["ReviewDecision", "executions"],
  ["Timeline", "executions"],
  ["VisionEvent", "events"],
]
const OPERATIONS = new Set([
  "alarms",
  "cameras",
  "events",
  "evidence",
  "executions",
  "health",
  "runtimes",
  "sops",
  "stations",
  "utils",
])

function groupFor(name) {
  const operation = /^([a-z]+)(?:[A-Z]|$)/.exec(name)?.[1]
  if (operation && OPERATIONS.has(operation)) return operation
  const prefix = MODEL_PREFIXES.find(([start]) => name.startsWith(start))
  return prefix?.[1] ?? "core"
}

const source = readFileSync(typesPath, "utf8")
const declarations = [...source.matchAll(/^export type (\w+)/gm)].map(
  (match) => ({
    name: match[1],
    index: match.index,
  }),
)
if (declarations.length === 0) {
  // Already split (the barrel only re-exports), so a second run is a no-op.
  if (/^export type \{/m.test(source)) process.exit(0)
  throw new Error(`${typesPath} has no exported types`)
}

// A declaration starts at its JSDoc when one sits directly above it.
function blockStart(index, floor) {
  const before = source.slice(floor, index)
  const jsdoc = before.lastIndexOf("/**")
  if (jsdoc < 0) return index
  return /^\/\*\*[\s\S]*\*\/\s*$/.test(before.slice(jsdoc))
    ? floor + jsdoc
    : index
}

const blocks = declarations.map((declaration, i) => {
  const start = blockStart(
    declaration.index,
    i === 0 ? 0 : declarations[i - 1].index,
  )
  const end =
    i + 1 < declarations.length
      ? blockStart(declarations[i + 1].index, declaration.index)
      : source.length
  return {
    name: declaration.name,
    group: groupFor(declaration.name),
    text: source.slice(start, end).trim(),
  }
})

const byGroup = new Map()
for (const block of blocks) {
  byGroup.set(block.group, [...(byGroup.get(block.group) ?? []), block])
}

// A type name appearing in another file's code is a reference. Comments are
// stripped first: a "@returns FooRead" note must not create an unused import
// (`noUnusedLocals` is on).
const codeOnly = (text) =>
  text.replace(/\/\*\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "")

function importLines(group, groupBlocks) {
  const code = codeOnly(groupBlocks.map((block) => block.text).join("\n"))
  const ownNames = new Set(groupBlocks.map((block) => block.name))
  const lines = []
  for (const [target, targetBlocks] of [...byGroup].sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    if (target === group) continue
    const used = targetBlocks
      .map((block) => block.name)
      .filter(
        (name) => !ownNames.has(name) && new RegExp(`\\b${name}\\b`).test(code),
      )
    if (used.length > 0)
      lines.push(
        `import type { ${used.sort().join(", ")} } from "./${target}.gen"`,
      )
  }
  return lines
}

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

for (const [group, groupBlocks] of byGroup) {
  const imports = importLines(group, groupBlocks)
  const body = groupBlocks.map((block) => block.text).join("\n\n")
  writeFileSync(
    join(outDir, `${group}.gen.ts`),
    `${HEADER}${imports.length > 0 ? `\n${imports.join("\n")}\n` : ""}\n${body}\n`,
  )
}

const barrel = [...byGroup]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([group, groupBlocks]) =>
      `export type { ${groupBlocks.map((block) => block.name).join(", ")} } from "./types/${group}.gen"`,
  )
writeFileSync(typesPath, `${HEADER}\n${barrel.join("\n")}\n`)

// Self-check: every declared name lands in exactly one split file.
const emitted = [...byGroup.values()].flat().map((block) => block.name)
if (
  emitted.length !== declarations.length ||
  new Set(emitted).size !== declarations.length
) {
  throw new Error(
    `split lost declarations: ${declarations.length} in, ${emitted.length} out`,
  )
}
